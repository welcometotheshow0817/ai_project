# 1. 2026년 기준 발로란트 티어 데이터 구조화 (딕셔너리 리스트)
# 'ratio'는 해당 티어의 비율, 'top'은 해당 티어의 시작 지점의 상위 누적 백분위입니다.
valorant_tiers = [
    {"rank": "아이언", "ratio": 6.5, "top": 100.0},
    {"rank": "브론즈", "ratio": 18.2, "top": 93.5},
    {"rank": "실버", "ratio": 23.4, "top": 75.3},
    {"rank": "골드", "ratio": 22.6, "top": 51.9},
    {"rank": "플래티넘", "ratio": 15.8, "top": 29.3},
    {"rank": "다이아몬드", "ratio": 8.5, "top": 13.5},
    {"rank": "초월자", "ratio": 3.9, "top": 5.0},
    {"rank": "불멸", "ratio": 1.0, "top": 1.1},
    {"rank": "레디언트", "ratio": 0.1, "top": 0.1},
]

def print_tier_table():
    """발로란트 티어 분포를 깔끔한 표 형태로 화면에 출력하는 함수"""
    print("\n" + "=" * 50)
    print(f" {'[2026 최신 기준] 발로란트 티어 분포도':^34}")
    print("=" * 50)
    print(f" {'티어 이름':<12} | {'유저 비율 (%)':<12} | {'상위 누적 (%)':<12}")
    print("-" * 50)
    
    # 레디언트(가장 높은 티어)부터 역순으로 출력하여 시각적 효과를 높임
    for tier in reversed(valorant_tiers):
        print(f" {tier['rank']:<14} | {tier['ratio']:<15}% | 상위 {tier['top']:<10}%")
    print("=" * 50)

def analyze_user_position(user_input):
    """사용자가 입력한 티어를 바탕으로 상위 몇 %인지 분석해주는 함수"""
    is_found = False
    
    for tier in valorant_tiers:
        if tier['rank'] == user_input:
            print("\n" + "★" * 40)
            print(f" 입력하신 티어: [{user_input}]")
            print(f" 분석 결과: 당신은 전체 발로란트 유저 중 '상위 {tier['top']}%' 이내에 분포합니다.")
            
            # 티어별 맞춤형 코멘트 추가 (알고리즘 분기 구조 심화)
            if tier['top'] <= 5.0:
                print(" -> 평가: 최상위권의 압도적인 실력자입니다!")
            elif tier['top'] <= 30.0:
                print(" -> 평가: 게임의 흐름을 잘 이해하고 있는 숙련자입니다.")
            elif tier['top'] <= 60.0:
                print(" -> 평가: 딱 대한민국 평균 수준의 실력을 가지고 있습니다.")
            else:
                print(" -> 평가: 아직 성장 가능성이 무궁무진한 유저입니다. 파이팅!")
            print("★" * 40)
            is_found = True
            break
            
    if not is_found:
        print("\n[오류] 올바른 티어 이름을 입력해주세요. (예: 아이언, 브론즈, 실버, 골드, 플래티넘...)")

# ==================== 프로그램 실행부 ====================
if __name__ == "__main__":
    print("■ 발로란트 데이터 분석 프로그램을 시작합니다. ■")
    
    # 1. 티어 표 출력 함수 호출
    print_tier_table()
    
    # 2. 사용자로부터 데이터 입력받기
    user_tier = input("\n당신의 발로란트 티어를 입력하세요 (예: 골드): ").strip()
    
    # 3. 입력 데이터 분석 함수 호출
    analyze_user_position(user_tier)
