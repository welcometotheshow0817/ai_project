# 1. 2026년 기준 발로란트 티어 데이터 설정
valorant_tiers = [
    {"rank": "레디언트", "ratio": "0.1%", "top": "상위 0.1%"},
    {"rank": "불멸", "ratio": "1.0%", "top": "상위 1.1%"},
    {"rank": "초월자", "ratio": "3.9%", "top": "상위 5.0%"},
    {"rank": "다이아몬드", "ratio": "8.5%", "top": "상위 13.5%"},
    {"rank": "플래티넘", "ratio": "15.8%", "top": "상위 29.3%"},
    {"rank": "골드", "ratio": "22.6%", "top": "상위 51.9%"},
    {"rank": "실버", "ratio": "23.4%", "top": "상위 75.3%"},
    {"rank": "브론즈", "ratio": "18.2%", "top": "상위 93.5%"},
    {"rank": "아이언", "ratio": "6.5%", "top": "상위 100.0%"},
]

# 2. 상단 타이틀 및 표 헤더 출력
print("==================================================")
print("      [2026년 최신 기준] 발로란트 티어 분포표")
print("==================================================")
print(" 티어이름\t│\t유저비율\t│\t상위누적")
print("--------------------------------------------------")

# 3. 반복문(for)을 이용해 깔끔하게 표로 출력
for tier in valorant_tiers:
    print(f" {tier['rank']}\t│\t{tier['ratio']}\t\t│\t{tier['top']}")
    
print("==================================================")

# 4. 사용자 입력 받기 (if문 조건 검색)
user_tier = input("\n자신의 티어를 입력하세요 (예: 골드): ")

# 5. 결과 분석 출력
for tier in valorant_tiers:
    if tier['rank'] in user_tier or user_tier in tier['rank']:
        print("\n" + "*" * 50)
        print(f" [분석 결과] 당신은 전체 유저 중 [{tier['top']}] 이내입니다.")
        print("*" * 50)
        break
